window.SUPPORTED_LANGS = Object.keys(translations);
window.getLang = () => {
  const l = document.documentElement.lang || "en";
  return translations[l] ? l : "en";
};
window.t = (key) => translations[window.getLang()]?.[key] || translations.en[key] || key;

window.applyTranslations = function () {
  const lang = window.getLang();
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = window.t(el.dataset.i18n).replace("{n}", (window.J999_CONFIG && window.J999_CONFIG.FREE_LIMIT) || 15);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = window.t(el.dataset.i18nPh); });
};

document.addEventListener("DOMContentLoaded", window.applyTranslations);
