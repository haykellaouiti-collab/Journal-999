window.getLang = () => {
  const l = document.documentElement.lang;
  return translations[l] ? l : "fr";
};
window.t = (key) => translations[window.getLang()]?.[key] || translations.fr[key] || key;

window.applyTranslations = function () {
  const lang = window.getLang();
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = window.t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = window.t(el.dataset.i18nPh);
  });
};

document.addEventListener("DOMContentLoaded", window.applyTranslations);
